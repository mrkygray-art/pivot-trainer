// Client-side PDF certificate. No server involved.
import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import type { SavedCertificate } from "./storage";

function hexToRgb(hex: string) {
  const n = parseInt(hex.replace("#", ""), 16);
  return rgb(((n >> 16) & 255) / 255, ((n >> 8) & 255) / 255, (n & 255) / 255);
}

export function newCertificateId() {
  const d = new Date();
  const stamp = `${d.getFullYear()}${String(d.getMonth() + 1).padStart(2, "0")}${String(d.getDate()).padStart(2, "0")}`;
  const rand = Math.random().toString(36).slice(2, 7).toUpperCase();
  return `PT-${stamp}-${rand}`;
}

export async function buildCertificatePdf(c: SavedCertificate): Promise<Uint8Array> {
  const pdf = await PDFDocument.create();
  pdf.setTitle(`Certificate - ${c.course}`);
  const page = pdf.addPage([792, 612]); // US Letter, landscape
  const { width, height } = page.getSize();
  const serif = await pdf.embedFont(StandardFonts.TimesRoman);
  const serifBold = await pdf.embedFont(StandardFonts.TimesRomanBold);
  const sans = await pdf.embedFont(StandardFonts.Helvetica);
  const sansBold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const primary = hexToRgb(c.colors.primary);
  const accent = hexToRgb(c.colors.accent);
  const ink = rgb(0.13, 0.13, 0.15);
  const muted = rgb(0.42, 0.42, 0.46);

  page.drawRectangle({ x: 24, y: 24, width: width - 48, height: height - 48, borderColor: primary, borderWidth: 3 });
  page.drawRectangle({ x: 34, y: 34, width: width - 68, height: height - 68, borderColor: accent, borderWidth: 1 });

  const center = (text: string, y: number, font = sans, size = 14, color = ink) => {
    // Keep long course titles inside the border.
    let s = size;
    while (font.widthOfTextAtSize(text, s) > width - 140 && s > 10) s -= 1;
    page.drawText(text, { x: (width - font.widthOfTextAtSize(text, s)) / 2, y, size: s, font, color });
  };

  center(c.organization.toUpperCase(), height - 90, sansBold, 12, primary);
  center("Certificate of Completion", height - 150, serifBold, 38, ink);
  center("This certifies that", height - 205, serif, 16, muted);
  center(c.learner, height - 255, serifBold, 34, primary);
  page.drawLine({ start: { x: width / 2 - 180, y: height - 268 }, end: { x: width / 2 + 180, y: height - 268 }, thickness: 1, color: accent });
  center("has completed the training", height - 300, serif, 16, muted);
  center(c.course, height - 340, serifBold, 22, ink);

  const date = new Date(c.date).toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric" });
  const cols = [
    ["DATE", date],
    ["SCORE", `${c.score}% first try`],
    ["CERTIFICATE ID", c.id],
  ];
  cols.forEach(([label, value], i) => {
    const x = 150 + i * 246;
    const lw = sansBold.widthOfTextAtSize(label, 9);
    const vw = sans.widthOfTextAtSize(value, 13);
    page.drawText(label, { x: x - lw / 2, y: 150, size: 9, font: sansBold, color: muted });
    page.drawText(value, { x: x - vw / 2, y: 130, size: 13, font: sans, color: ink });
  });

  center("Generated by Pivot Trainer, an independent prototype. Organization and content are fictional.", 60, sans, 9, muted);
  return pdf.save();
}

export async function downloadCertificate(c: SavedCertificate) {
  const bytes = await buildCertificatePdf(c);
  const blob = new Blob([bytes as BlobPart], { type: "application/pdf" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `certificate-${c.id}.pdf`;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
